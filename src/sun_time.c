int is_daytime(const hal_rtc_time_t *time)
{
    int day = day_of_year(time);
    if (day < 0 || day >= 366) {
        return -1; // Invalid day
    }

    uint8_t sunrise_offset = sun_rise_offset[day];
    uint8_t sunset_offset = sun_set_offset[day];

    rtc_time_point_t sunrise_time = {
        .hour = sun_rise_ref.hour + sunrise_offset / 60,
        .min = sun_rise_ref.min + sunrise_offset % 60,
        .sec = sun_rise_ref.sec
    };
    if (sunrise_time.min >= 60) {
        sunrise_time.hour += sunrise_time.min / 60;
        sunrise_time.min %= 60;
    }
    if (sunrise_time.hour >= 24) {
        sunrise_time.hour %= 24;
    }

    rtc_time_point_t sunset_time = {
        .hour = sun_set_ref.hour + sunset_offset / 60,
        .min = sun_set_ref.min + sunset_offset % 60,
        .sec = sun_set_ref.sec
    };
    if (sunset_time.min >= 60) {
        sunset_time.hour += sunset_time.min / 60;
        sunset_time.min %= 60;
    }
    if (sunset_time.hour >= 24) {
        sunset_time.hour %= 24;
    }

    int current_minutes = time->hour * 60 + time->min;
    int sunrise_minutes = sunrise_time.hour * 60 + sunrise_time.min;
    int sunset_minutes = sunset_time.hour * 60 + sunset_time.min;

    return (current_minutes >= sunrise_minutes && current_minutes < sunset_minutes) ? 1 : 0;
}